#!/usr/bin/env python3
"""Generate a compact LVGL vector basemap from the checked-in OSM extract.
Map data © OpenStreetMap contributors, ODbL 1.0. See assets/maps/README.md.
No network access, dependencies or raster framebuffer required.
"""
import math
import pathlib
import xml.etree.ElementTree as ET
ROOT = pathlib.Path(__file__).resolve().parents[1]
ORIGIN = (-37.8361917, 145.0852289)
root = ET.parse(ROOT / 'assets/maps/highfield.osm').getroot()
nodes = {n.attrib['id']: (float(n.attrib['lat']), float(n.attrib['lon'])) for n in root.findall('node')}

def point(lat, lon):
    return (round((lon - ORIGIN[1]) * 111319.5 * math.cos(math.radians(ORIGIN[0]))), round((lat - ORIGIN[0]) * 111319.5))

def cross(a,b,c):
    return (b[0]-a[0])*(c[1]-a[1])-(b[1]-a[1])*(c[0]-a[0])

def triangles(points):
    ids=list(range(len(points)))
    area=sum(points[i][0]*points[(i+1)%len(points)][1]-points[(i+1)%len(points)][0]*points[i][1] for i in ids)
    if area<0: ids.reverse()
    result=[]
    while len(ids)>3:
        for j,b in enumerate(ids):
            a,c=ids[j-1],ids[(j+1)%len(ids)]
            if cross(points[a],points[b],points[c])<=0: continue
            if any(cross(points[a],points[b],points[d])>=0 and cross(points[b],points[c],points[d])>=0 and cross(points[c],points[a],points[d])>=0 for d in ids if d not in (a,b,c)): continue
            result.append((a,b,c));ids.pop(j);break
        else: raise ValueError('Cannot triangulate OSM polygon')
    if len(ids)==3: result.append(tuple(ids))
    return result

features=[]
for way in root.findall('way'):
    tags={t.attrib['k']:t.attrib['v'] for t in way.findall('tag')}
    kind=None
    if tags.get('leisure')=='park': kind=0
    elif tags.get('leisure')=='pitch': kind=1
    elif 'building' in tags: kind=2
    elif tags.get('amenity')=='parking' or tags.get('leisure')=='playground':kind=3
    elif tags.get('highway') in ('footway','path','cycleway','steps'):kind=4
    elif 'highway' in tags and tags['highway'] not in ('construction','proposed'):kind=5
    if kind is None:continue
    pts=[]
    for nd in way.findall('nd'):
        p=point(*nodes[nd.attrib['ref']])
        if not pts or p!=pts[-1]:pts.append(p)
    if kind<4:
        if pts[0]==pts[-1]:pts.pop()
        # Integer rounding can leave collinear or duplicate vertices.
        changed=True
        while changed and len(pts)>3:
            changed=False
            for i in range(len(pts)):
                if cross(pts[i-1],pts[i],pts[(i+1)%len(pts)])==0:
                    pts.pop(i);changed=True;break
        if len(pts)<3:continue
    if len(pts)<2:continue
    if max(p[0] for p in pts)<-410 or min(p[0] for p in pts)>430 or max(p[1] for p in pts)<-425 or min(p[1] for p in pts)>470:continue
    features.append((kind,pts))
features.sort(key=lambda f:f[0])
vertices=[];fills=[];paths=[]
for kind,pts in features:
    offset=len(vertices);vertices.extend(pts)
    if kind<4:
        for a,b,c in triangles(pts):fills.append((offset+a,offset+b,offset+c,kind))
    paths.append((offset,len(pts),kind))
assert len(vertices)<65536 and all(-32768<=v<=32767 for point in vertices for v in point)
lines=['// Generated by tools/generate_highfield_map.py. Do not edit.', '// Map data © OpenStreetMap contributors (ODbL 1.0).', 'static const MapVertex mapVertices[] = {']
lines += [f'{{{x},{y}}},' for x,y in vertices];lines+=['};','static const MapTriangle mapTriangles[] = {']
lines += ['{%s},'%','.join(map(str,t)) for t in fills];lines+=['};','static const MapPath mapPaths[] = {']
lines += ['{%s},'%','.join(map(str,p)) for p in paths];lines+=['};']
(ROOT/'src/highfield_map_data.inc').write_text('\n'.join(lines)+'\n')
print(f'{len(vertices)} vertices, {len(fills)} triangles, {len(paths)} paths; approx {len(vertices)*4+len(fills)*8+len(paths)*6} bytes flash')
