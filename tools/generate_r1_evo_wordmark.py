#!/usr/bin/env python3
"""Original vector lettering inspired by the R-1 badge; no font dependency.
Regenerate SVG, transparent preview and LVGL RGB565+alpha asset with Pillow.
"""
from pathlib import Path
import sys
from PIL import Image, ImageDraw
sys.path.insert(0, str(Path(__file__).parent))
from png_to_lvgl_rgb565 import export_image

ROOT = Path(__file__).resolve().parents[1]
# Proportions from the standalone cover artwork (PDF page 4 of 496148.pdf).
# Smooth the bowl using the physical decal reference; the PDF is faceted.
def curve(start, c1, c2, end, steps=16):
    return [tuple((1-t)**3*start[j] + 3*(1-t)**2*t*c1[j]
                  + 3*(1-t)*t*t*c2[j] + t**3*end[j] for j in (0,1))
            for t in [i/steps for i in range(1,steps+1)]]

bowl = [(94,61),(158,61)]
bowl += curve((158,61),(190,61),(202,69),(198,90))
bowl += curve((198,90),(195,113),(185,126),(155,126))
bowl += [(104,126),(88,167),(54,167),(78,102),(151,102)]
bowl += curve((151,102),(164,102),(167,87),(149,87))
bowl += [(84,87)]
# One common sloping guide joins both serif ends and the dash's right edge.
# Move the 1 right to keep the longer decal dash and a clear gap to its stem.
def serif_edge(y): return 292 - 0.44 * (y - 54)
reference = [
    bowl,
    [(122,130),(158,130),(185,167),(148,167)],
    # Physical decal has a longer dash than the manual artwork.
    [(207,95),(serif_edge(95),95),(serif_edge(118),118),(198,118)],
    [(serif_edge(54),54),(347,54),(307,167),(serif_edge(167),167),(serif_edge(145),145),(282,145),(306,79),(serif_edge(79),79)],
    [(321,145),(358,145),(351,167),(314,167)],
]
shapes = [('#edb52c', [(x-54+4,y-53+4) for x,y in pts]) for pts in reference]
# Matching original EVO lettering: the same forward rake and open stencil cut.
# Round both contours of the O before applying the rake, so its shoulders echo
# the smooth R bowl rather than introducing chamfered corners.
o_outer = [(164,0),(187,0)]
o_outer += curve((187,0),(201,0),(206,6),(206,20))
o_outer += [(206,56)]
o_outer += curve((206,56),(206,70),(201,76),(187,76))
o_outer += [(164,76)]
o_outer += curve((164,76),(150,76),(145,70),(145,56))
o_outer += [(145,20)]
o_outer += curve((145,20),(145,6),(150,0),(164,0))
o_inner = [(173,18),(178,18)]
o_inner += curve((178,18),(183,18),(185,21),(185,26))
o_inner += [(185,50)]
o_inner += curve((185,50),(185,55),(183,58),(178,58))
o_inner += [(173,58)]
o_inner += curve((173,58),(168,58),(166,55),(166,50))
o_inner += [(166,26)]
o_inner += curve((166,26),(166,21),(168,18),(173,18))
evo = [
    [(0,0),(56,0),(56,17),(0,17)],
    [(0,27),(51,27),(51,44),(21,44),(21,59),(56,59),(56,76),(0,76)],
    [(67,0),(89,0),(101,53),(114,0),(136,0),(115,76),(87,76)],
    o_outer,
]
def evo_point(x,y): return (332 + (x + 27-y*0.35)*1.45, 8+y*1.45)
shapes += [('#dce5e8', [evo_point(x,y) for x,y in pts]) for pts in evo]
hole = [evo_point(x,y) for x,y in o_inner]
def rake(points): return points # Geometry already includes each glyph's rake.
w,h = 670,122
scale=4
im=Image.new('RGBA',(w*scale,h*scale))
draw=ImageDraw.Draw(im)
svg=[f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}"><title>R-1 EVO custom wordmark</title>']
for index,(color,points) in enumerate(shapes):
    points=rake(points)
    draw.polygon([(round(x*scale),round(y*scale)) for x,y in points], fill=color)
    path='M'+' L'.join(f'{x:.2f},{y:.2f}' for x,y in points)+' Z'
    if index==len(shapes)-1:
        inner=rake(hole)
        draw.polygon([(round(x*scale),round(y*scale)) for x,y in inner],fill=(0,0,0,0))
        path+=' M'+' L'.join(f'{x:.2f},{y:.2f}' for x,y in inner)+' Z'
    svg.append(f'<path fill="{color}" fill-rule="evenodd" d="{path}"/>')
svg.append('</svg>')
(ROOT/'assets/r1-evo-wordmark.svg').write_text('\n'.join(svg)+'\n')
# Native portrait size: no runtime scaling or full font required.
preview=ROOT/'assets/r1-evo-wordmark.png'
cpp=export_image(im,(280,52),'r1_evo_wordmark',preview)
(ROOT/'src/r1_evo_wordmark.cpp').write_text('// Generated by tools/generate_r1_evo_wordmark.py\n#include <lvgl.h>\n\n'+cpp)
