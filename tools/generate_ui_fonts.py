#!/usr/bin/env python3
"""Generate the six checked-in V2 LVGL bitmap fonts from licensed source TTFs.

Prerequisites (local, ignored):
  npm install --prefix tmp/font-tools lv_font_conv@1.5.3
  .venv/bin/python -m pip install --target tmp/font-tools/python fonttools==4.68.0
Run with .venv/bin/python tools/generate_ui_fonts.py. No network at generation.
"""
from pathlib import Path
import hashlib
import json
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tmp/font-tools/python'))
import fontTools
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont


def main():
    assert fontTools.__version__ == '4.68.0', fontTools.__version__
    assets = ROOT / 'assets/fonts'
    manifest = json.loads((assets / 'sources.json').read_text())
    for name, item in manifest['files'].items():
        assert hashlib.sha256((assets / name).read_bytes()).hexdigest() == item['sha256'], name
    work = ROOT / 'tmp/font-tools/instances'
    work.mkdir(parents=True, exist_ok=True)
    out = ROOT / 'src/fonts'
    out.mkdir(exist_ok=True)
    converter = ROOT / 'tmp/font-tools/node_modules/.bin/lv_font_conv'
    version = subprocess.check_output([str(converter), '--version'], text=True).strip()
    assert version == '1.5.3', version
    for family, weight, sizes in [('DMSans', 500, [12]), ('DMSans', 600, [14, 16]), ('Manrope', 800, [22, 32, 48])]:
        variable = TTFont(assets / (family + '-Variable.ttf'))
        axes = {'wght': weight}
        if family == 'DMSans':
            axes['opsz'] = 14
        instance = instantiateVariableFont(variable, axes, inplace=False)
        ttf = work / f'{family}-{weight}.ttf'
        instance.save(ttf)
        for size in sizes:
            name = f'r1_{"dm" if family == "DMSans" else "manrope"}_{size}'
            target = out / (name + '.inc')
            subprocess.run([str(converter), '--font', str(ttf), '--range', ('0x20-0x7e,0xa0,0xb0,0xd7,0x2013-0x2014,0x2022,0x2026,0x2212' + (',0x2190-0x2193' if family == 'DMSans' else '')),
                            '--size', str(size), '--bpp', '4', '--format', 'lvgl', '--no-compress',
                            '--lv-font-name', name, '--lv-fallback', f'r1_symbols_{size}', '-o', str(target)], check=True)
            # Converter comments otherwise include this machine's absolute paths.
            text = target.read_text().replace(str(ROOT) + '/', '')
            target.write_text('// Generated by tools/generate_ui_fonts.py. See assets/fonts for OFL licences.\n' + text)
            print(target.relative_to(ROOT), target.stat().st_size)
    # Exact source-bitmap subsetting, independent of the TTF rasterizer.
    from generate_symbol_fonts import generated
    for path, text in generated().items():
        path.write_text(text)


if __name__ == '__main__':
    main()
