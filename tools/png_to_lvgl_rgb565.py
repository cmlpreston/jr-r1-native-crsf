#!/usr/bin/env python3
"""Export transparent header/widget artwork as LVGL v8 RGB565 + alpha assets."""

from pathlib import Path
import sys

from PIL import Image


def export_image(source: Image.Image, size: tuple[int, int], symbol: str,
                 preview: Path) -> str:
    width, height = size
    source = source.copy()
    source.thumbnail((width - 4, height - 4), Image.Resampling.LANCZOS)
    canvas = Image.new("RGBA", size, (0, 0, 0, 0))
    canvas.alpha_composite(source, ((width - source.width) // 2,
                                   (height - source.height) // 2))
    canvas.save(preview)

    # LVGL's 16-bit true-colour-alpha format: RGB565 little endian, then alpha.
    raw = bytearray()
    pixels = canvas.tobytes()
    for offset in range(0, len(pixels), 4):
        red, green, blue, alpha = pixels[offset:offset + 4]
        pixel = ((red & 0xF8) << 8) | ((green & 0xFC) << 3) | (blue >> 3)
        raw.extend((pixel & 0xFF, pixel >> 8, alpha))
    rows = []
    for offset in range(0, len(raw), 16):
        rows.append("    " + ", ".join(f"0x{byte:02x}" for byte in raw[offset:offset + 16]))
    data = ",\n".join(rows)
    return f'''const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST uint8_t {symbol}_map[] = {{
{data}
}};

extern const lv_img_dsc_t {symbol} = {{
    .header = {{
        .cf = LV_IMG_CF_TRUE_COLOR_ALPHA,
        .always_zero = 0,
        .reserved = 0,
        .w = {width},
        .h = {height},
    }},
    .data_size = sizeof({symbol}_map),
    .data = {symbol}_map,
}};
'''


def main() -> None:
    if len(sys.argv) != 4:
        raise SystemExit("usage: png_to_lvgl_rgb565.py INPUT OUTPUT_CPP OUTPUT_PREVIEW")
    source = Image.open(sys.argv[1]).convert("RGBA")
    bounds = source.getchannel("A").getbbox()
    if bounds is None:
        raise SystemExit("input contains no visible pixels")
    source = source.crop(bounds)
    preview = Path(sys.argv[3])
    output = "// Generated by tools/png_to_lvgl_rgb565.py; retain source alpha.\n#include <lvgl.h>\n\n"
    output += export_image(source, (82, 58), "hyper7_icon", preview)
    output += "\n" + export_image(source, (240, 160), "hyper7_widget_icon",
                                 preview.with_name("hyper7-buggy-widget.png"))
    Path(sys.argv[2]).write_text(output)


if __name__ == "__main__":
    main()
