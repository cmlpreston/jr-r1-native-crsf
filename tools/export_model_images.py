#!/usr/bin/env python3
"""Convert original gallery assets to display-sized LVGL RGB565+alpha data."""
from pathlib import Path
from PIL import Image
from png_to_lvgl_rgb565 import export_image
root=Path(__file__).resolve().parents[1]
names=['buggy','truggy','short-course','monster-truck','crawler','touring','formula']
out=['// Generated by tools/export_model_images.py\n#include <lvgl.h>\n']
for name in names:
 im=Image.open(root/'assets/model-images/originals'/f'{name}.png').convert('RGBA')
 out.append(export_image(im,(160,108),'model_'+name.replace('-','_'),root/'assets/model-images'/f'{name}.png'))
(root/'src/model_image_assets.cpp').write_text('\n'.join(out))
