#!/usr/bin/env python3
"""Subset pinned LVGL bitmap fonts without rerasterizing any glyph.

The six UI faces already contain ordinary text. Keep the symbols referenced by
the handset and LVGL widgets/themes as their fallbacks. Preserve the former
LVGL default's ASCII/degree/bullet glyphs and kerning in a separate 14px font.
No network, TTF converter or third-party Python modules are needed.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[1]
SIZES = (12, 14, 16, 22, 32, 48)
MANIFEST = ROOT / 'assets/fonts/symbol-sources.json'
LVGL = ROOT / 'simulator/third_party/lvgl'
if not (LVGL / 'src/font/lv_font.h').is_file():
    LVGL = ROOT / '.pio/libdeps/seeed_xiao_esp32s3-pcb/lvgl'


def array(text, name):
    body = re.search(r'\b' + name + r'\[\]\s*=\s*\{(.*?)\};', text, re.S).group(1)
    body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
    return [int(value, 0) for value in re.findall(r'-?0x[\da-fA-F]+|-?\d+', body)]


def load_font(size):
    path = LVGL / f'src/font/lv_font_montserrat_{size}.c'
    text = path.read_text()
    expected = json.loads(MANIFEST.read_text())['sha256'][str(size)]
    if hashlib.sha256(path.read_bytes()).hexdigest() != expected:
        raise ValueError(f'Unreviewed LVGL source font: {path}')
    body = re.search(r'\bglyph_dsc\[\]\s*=\s*\{(.*?)\n\};', text, re.S).group(1)
    descriptors = [dict((key, int(value)) for key, value in
        re.findall(r'\.(\w+)\s*=\s*(-?\d+)', row)) for row in re.findall(r'\{([^{}]+)\}', body)]
    mapping = {code: code - 31 for code in range(32, 127)}
    mapping.update({176 + offset: 96 + index for index, offset in enumerate(array(text, 'unicode_list_1'))})
    metrics = {key: int(re.search(r'\.' + key + r'\s*=\s*(-?\d+)', text).group(1))
               for key in ('line_height', 'base_line', 'underline_position', 'underline_thickness')}
    return dict(text=text, bitmap=array(text, 'glyph_bitmap'), descriptors=descriptors,
                mapping=mapping, metrics=metrics, left=array(text, 'kern_left_class_mapping'),
                right=array(text, 'kern_right_class_mapping'), kern=array(text, 'kern_class_values'))


def referenced_symbols():
    paths = [*ROOT.glob('src/*.cpp'), *ROOT.glob('src/*.inc'), *ROOT.glob('include/*.h')]
    for directory in ('src/widgets', 'src/extra/widgets', 'src/extra/themes', 'src/core'):
        paths.extend((LVGL / directory).rglob('*.[ch]'))
    names = set()
    for path in paths:
        if path.name == 'setup_portal_page.h':
            continue  # Browser text does not use the LCD's bitmap fonts.
        tokens=re.compile(r'//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\])*"',re.S)
        text = tokens.sub(lambda match: '' if match.group().startswith(('//','/*')) else match.group(),path.read_text())
        names.update(re.findall(r'\bLV_SYMBOL_[A-Z0-9_]+\b', text))
    definitions = (LVGL / 'src/font/lv_symbol_def.h').read_text()
    result = {}
    for name in sorted(names):
        if name in ('LV_SYMBOL_DUMMY', 'LV_SYMBOL_BULLET'):
            continue  # Non-rendering image prefix / supplied by the primary face.
        match = re.search(r'#define\s+' + name + r'\s+"([^"]+)"', definitions)
        if not match:
            raise ValueError(f'Unknown LVGL symbol: {name}')
        escaped = match.group(1)
        value = bytes(int(value, 16) for value in re.findall(r'\\x([\da-fA-F]{2})', escaped)).decode('utf8')
        if len(value) != 1:
            raise ValueError(f'Expected one symbol codepoint: {name}')
        result[name] = ord(value)
    return result


def emit_array(name, ctype, values, per_line=12):
    rows = [f'static const {ctype} {name}[] = {{']
    rows.extend('    ' + ', '.join(str(v) for v in values[n:n + per_line]) + ','
                for n in range(0, len(values), per_line))
    return '\n'.join([*rows, '};'])


def render_font(size, points, default=False):
    source = load_font(size)
    name = 'r1_default_14' if default else f'r1_symbols_{size}'
    points = sorted(points)
    bitmap, glyphs = [], [dict(bitmap_index=0, adv_w=0, box_w=0, box_h=0, ofs_x=0, ofs_y=0)]
    for point in points:
        gid = source['mapping'][point]
        original = source['descriptors'][gid]
        end = source['descriptors'][gid + 1]['bitmap_index'] if gid + 1 < len(source['descriptors']) else len(source['bitmap'])
        glyphs.append(dict(original, bitmap_index=len(bitmap)))
        bitmap.extend(source['bitmap'][original['bitmap_index']:end])
        if not default and (source['left'][gid] or source['right'][gid]):
            raise ValueError('A symbol gained kerning; subset generation needs review')
    sections = [f'''// Generated by tools/generate_symbol_fonts.py; do not edit.
// LVGL 8.4.0 bitmap data, copied without rasterization or metric changes.
// Copyright (c) 2021 LVGL Kft. MIT licence: assets/fonts/LVGL-MIT.txt.
// Symbols derive from the FontAwesome font distributed with LVGL.
// Source SHA-256: {json.loads(MANIFEST.read_text())['sha256'][str(size)]}
''', emit_array(name + '_bitmap', 'uint8_t', bitmap)]
    sections.append(f'static const lv_font_fmt_txt_glyph_dsc_t {name}_glyphs[] = {{\n' + '\n'.join(
        '    {' + ', '.join(f'.{key} = {value}' for key, value in glyph.items()) + '},' for glyph in glyphs) + '\n};')
    if default:
        normal = [point for point in points if point >= 127]
        sections.append(emit_array(name + '_unicode', 'uint16_t', [point - normal[0] for point in normal]))
        maps = [f'{{32, 95, 1, NULL, NULL, 0, LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}}',
                f'{{{normal[0]}, {normal[-1]-normal[0]+1}, 96, {name}_unicode, NULL, {len(normal)}, LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}}']
        sections.extend([emit_array(name + '_left', 'uint8_t', source['left'][:len(glyphs)]),
                         emit_array(name + '_right', 'uint8_t', source['right'][:len(glyphs)]),
                         emit_array(name + '_kern', 'int8_t', source['kern'])])
        sections.append(f'''static const lv_font_fmt_txt_kern_classes_t {name}_classes = {{
    {name}_kern, {name}_left, {name}_right, 61, 49
}};''')
        kern, scale, classes = '&' + name + '_classes', 16, 1
    else:
        sections.append(emit_array(name + '_unicode', 'uint16_t', [point - points[0] for point in points]))
        maps = [f'{{{points[0]}, {points[-1]-points[0]+1}, 1, {name}_unicode, NULL, {len(points)}, LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}}']
        kern, scale, classes = 'NULL', 0, 0
    sections.append(f'static const lv_font_fmt_txt_cmap_t {name}_maps[] = {{\n    ' + ',\n    '.join(maps) + '\n};')
    sections.append(f'''static lv_font_fmt_txt_glyph_cache_t {name}_cache;
static const lv_font_fmt_txt_dsc_t {name}_description = {{
    .glyph_bitmap = {name}_bitmap,
    .glyph_dsc = {name}_glyphs,
    .cmaps = {name}_maps,
    .kern_dsc = {kern},
    .kern_scale = {scale},
    .cmap_num = {len(maps)},
    .bpp = 4,
    .kern_classes = {classes},
    .bitmap_format = 0,
    .cache = &{name}_cache
}};
const lv_font_t {name} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {source['metrics']['line_height']},
    .base_line = {source['metrics']['base_line']},
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = {source['metrics']['underline_position']},
    .underline_thickness = {source['metrics']['underline_thickness']},
    .dsc = &{name}_description,
    .fallback = {'&r1_symbols_14' if default else 'NULL'},
    .user_data = NULL
}};''')
    return '\n\n'.join(sections) + '\n'


def generated():
    symbols = referenced_symbols()
    points = set(symbols.values())
    output = {ROOT / f'src/fonts/r1_symbols_{size}.inc': render_font(size, points) for size in SIZES}
    output[ROOT / 'src/fonts/r1_default_14.inc'] = render_font(14, {*range(32, 127), 176, 8226}, True)
    output[ROOT / 'assets/fonts/symbol-repertoire.json'] = json.dumps(symbols, indent=2, sort_keys=True) + '\n'
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if generated assets need regeneration')
    args = parser.parse_args()
    for path, text in generated().items():
        if args.check:
            if not path.is_file() or path.read_text() != text:
                raise SystemExit(f'Regenerate symbol fonts: {path.relative_to(ROOT)}')
        else:
            path.write_text(text)
    print('Symbol fonts: pinned source hashes and generated repertoire verified' if args.check else 'Generated exact symbol subsets and preserved LVGL default')


if __name__ == '__main__':
    main()
